import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

// Android must never receive a Vite bundle which silently falls back to the
// demo driver. Read the same public variables Vite uses, then pass them to
// Vite explicitly and inspect the finished bundle before Capacitor can copy it.
const configFiles = ['.env', '.env.production', '.env.local', '.env.production.local'];
const values = { ...process.env };

for (const file of configFiles) {
  if (!existsSync(file)) continue;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (!match) continue;
    values[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
  }
}

const url = (values.VITE_SUPABASE_URL ?? '').trim();
const key = (values.VITE_SUPABASE_ANON_KEY ?? '').trim();
const apiBaseUrl = (values.VITE_EXY_API_BASE_URL ?? 'https://exy-green.vercel.app').trim().replace(/\/+$/, '');
const releaseVersion = JSON.parse(readFileSync('package.json', 'utf8')).version;
const releaseMarker = `EXY_RELEASE_VERSION:${releaseVersion}`;

if (!/^\d+\.\d+\.\d+$/.test(releaseVersion)) {
  console.error('EXY Android build blocked: package.json must contain a semantic release version.');
  process.exit(1);
}

// Keep Android's native package identity tied to the same version printed in
// the web footer. Previously Gradle contained a stale hard-coded value, so a
// correctly copied web bundle could still be packaged as an older APK. The
// monotonic value also lets Android replace an older installed build.
const [releaseMajor, releaseMinor, releasePatch] = releaseVersion.split('.').map(Number);
const androidVersionCode = releaseMajor * 1_000_000 + releaseMinor * 1_000 + releasePatch;
const gradlePath = 'android/app/build.gradle';
if (!existsSync(gradlePath)) {
  console.error(`EXY Android build blocked: ${gradlePath} is missing.`);
  process.exit(1);
}
const gradleSource = readFileSync(gradlePath, 'utf8');
const gradleVersioned = gradleSource
  .replace(/versionCode\s+\d+/, `versionCode ${androidVersionCode}`)
  .replace(/versionName\s+["'][^"']+["']/, `versionName "${releaseVersion}"`);
// A second preparation run may find the version fields already correct. That
// is valid: this command must be safe to rerun before a clean APK build.
if (!gradleVersioned.includes(`versionCode ${androidVersionCode}`) || !gradleVersioned.includes(`versionName "${releaseVersion}"`)) {
  console.error('EXY Android build blocked: could not synchronize native Android version fields.');
  process.exit(1);
}
writeFileSync(gradlePath, gradleVersioned, 'utf8');
console.log(`EXY Android native version synchronized: ${releaseVersion} (versionCode ${androidVersionCode}).`);

if (!url || !key) {
  console.error('EXY Android build blocked: VITE_SUPABASE_URL or VITE_SUPABASE_ANON_KEY is missing.');
  process.exit(1);
}

let host = '';
try {
  const parsed = new URL(url);
  if (parsed.protocol !== 'https:' || !parsed.hostname.endsWith('.supabase.co')) throw new Error('invalid host');
  host = parsed.host;
} catch {
  console.error('EXY Android build blocked: VITE_SUPABASE_URL must be a valid HTTPS *.supabase.co URL.');
  process.exit(1);
}

if (key.length < 20 || /your_|placeholder|example|test\.signature/i.test(key)) {
  console.error('EXY Android build blocked: VITE_SUPABASE_ANON_KEY is missing or is a placeholder.');
  process.exit(1);
}

try {
  const parsed = new URL(apiBaseUrl);
  if (parsed.protocol !== 'https:') throw new Error('not https');
} catch {
  console.error('EXY Android build blocked: VITE_EXY_API_BASE_URL must be a valid HTTPS URL.');
  process.exit(1);
}

const viteCli = join(process.cwd(), 'node_modules', 'vite', 'bin', 'vite.js');
const capacitorCli = join(process.cwd(), 'node_modules', '@capacitor', 'cli', 'bin', 'capacitor');

function runNodeCli(label, script, args) {
  const result = spawnSync(process.execPath, [script, ...args], {
    cwd: process.cwd(),
    stdio: 'inherit',
    env: values,
  });
  if (result.error) {
    console.error(`EXY Android build blocked: could not start ${label}: ${result.error.message}`);
    process.exit(1);
  }
  if (result.status !== 0) {
    console.error(`EXY Android build blocked: ${label} exited with code ${result.status ?? 'unknown'}.`);
    process.exit(result.status ?? 1);
  }
}

// Do not rely only on Vite's .env discovery. Write the public Android
// settings into a generated module which is imported by the app. This removes
// environment-mode ambiguity and makes the exact configuration testable after
// Capacitor has copied the web bundle into Android.
mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/buildConfig.ts',
  `// Generated by scripts/build-android-production.mjs. Do not edit.\nexport const androidBuildConfig = {\n  supabaseUrl: ${JSON.stringify(url)},\n  supabaseAnonKey: ${JSON.stringify(key)},\n  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},\n  stamp: ${JSON.stringify(`EXY_ANDROID_PRODUCTION:${host}`)},\n  releaseVersion: ${JSON.stringify(releaseVersion)},\n  releaseMarker: ${JSON.stringify(releaseMarker)},\n} as const;\n`,
  'utf8',
);

// A physical build-info file survives Vite's tree-shaking. Its presence in
// Android assets proves exactly which web bundle Gradle will package.
mkdirSync('public', { recursive: true });
writeFileSync(
  'public/exy-build-info.json',
  JSON.stringify(
    {
      releaseVersion,
      releaseMarker,
      supabaseHost: host,
      apiBaseUrl,
      supabaseStamp: `EXY_ANDROID_PRODUCTION:${host}`,
    },
    null,
    2,
  ) + '\n',
  'utf8',
);

runNodeCli('Vite production build', viteCli, ['build', '--mode', 'production']);

function bundleContains(directory, text) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory() && bundleContains(path, text)) return true;
    if (entry.isFile() && readFileSync(path, 'utf8').includes(text)) return true;
  }
  return false;
}

if (
  !existsSync('dist') ||
  !existsSync('dist/exy-build-info.json') ||
  !readFileSync('dist/exy-build-info.json', 'utf8').includes(releaseMarker) ||
  !bundleContains('dist', host) ||
  !bundleContains('dist', apiBaseUrl) ||
  !bundleContains('dist', `EXY_ANDROID_PRODUCTION:${host}`) ||
  !bundleContains('dist', releaseMarker) ||
  bundleContains('dist', 'test.signature')
) {
  console.error(`EXY Android build blocked: the verified production configuration or ${releaseMarker} was not embedded in the web bundle.`);
  process.exit(1);
}

// Capacitor's public asset directory is generated output. Clear only this
// narrow directory before copying so Gradle can never reuse a prior web bundle.
const androidAssets = 'android/app/src/main/assets/public';
rmSync(androidAssets, { recursive: true, force: true });

runNodeCli('Capacitor Android copy', capacitorCli, ['copy', 'android']);

const verify = spawnSync(process.execPath, ['scripts/verify-android-assets.mjs'], {
  cwd: process.cwd(),
  stdio: 'inherit',
  env: values,
});
if (verify.error) {
  console.error(`EXY Android build blocked: could not verify Android assets: ${verify.error.message}`);
  process.exit(1);
}
if (verify.status !== 0) process.exit(verify.status ?? 1);

console.log(`EXY Android bundle verified for production Supabase: ${host} · version ${releaseVersion}`);
